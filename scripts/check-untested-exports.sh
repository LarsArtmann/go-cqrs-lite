#!/usr/bin/env bash
# check-untested-exports.sh — every exported symbol must be NAMED somewhere in
# a test file, or be on the frozen debt list.
#
# Why this exists: docs/api_surface.txt already enumerates the promise the
# library makes (6,334 exported symbols at the 2026-10-26 census). Nothing
# checked whether that promise is exercised: 1,088 of those symbols were never
# mentioned in ANY test file. A symbol with no test reference is API nobody
# has ever verified — the compiler proves it exists, not that it works.
#
# The gate is a RATCHET, not a cleanup order:
#   * a NEW exported symbol with no test reference fails CI,
#   * an existing one is allowed only while it is on the frozen debt list
#     (scripts/untested-exports-baseline.txt, 1,088 rows on 2026-10-26),
#   * rows that gained a test are reported STALE and can be pruned with
#     --update; the list only shrinks.
#
# The check is name-based: it proves a symbol is mentioned by a test, not that
# the mention asserts behavior (idea #4, the zero-assertion gate, covers that).
# False negatives (a name that coincidentally appears) are acceptable for a
# ratchet; false positives are not, which is why the whole repo's tests count —
# a symbol exercised by an integration or system-level test IS tested.
#
# Usage: bash scripts/check-untested-exports.sh [flags]
#   (default)     verify against the frozen list; exit 1 on any new symbol
#   --update      rewrite the frozen list from the current tree
#   --self-test   fault-inject the compare logic against fixtures
#   --quiet       print only failures and the summary
#   --help
#
# Environment:
#   UNTESTED_EXPORTS_BASELINE  list path (default scripts/untested-exports-baseline.txt)
#   API_SURFACE                golden path (default docs/api_surface.txt)

set -euo pipefail
export LC_ALL=C

cd "$(git rev-parse --show-toplevel)"

BASELINE="${UNTESTED_EXPORTS_BASELINE:-scripts/untested-exports-baseline.txt}"
SURFACE="${API_SURFACE:-docs/api_surface.txt}"
MODE=gate
QUIET=0

die() {
	echo "::error::$1" >&2
	exit 1
}

usage() {
	sed -n '2,/^$/p' "$0" | sed 's/^# \{0,1\}//'
}

while [ $# -gt 0 ]; do
	case "$1" in
	--update) MODE=update ;;
	--self-test) MODE=selftest ;;
	--quiet) QUIET=1 ;;
	--help | -h)
		usage
		exit 0
		;;
	*) die "unknown flag: $1 (try --help)" ;;
	esac
	shift
done

# build_corpus writes every identifier that appears in any test file.
build_corpus() { # $1=out
	find . -name '*_test.go' \
		-not -path './vendor/*' \
		-not -path '*/testdata/*' \
		-not -path './node_modules/*' \
		-print0 |
		xargs -0 cat 2>/dev/null | tr -cs 'A-Za-z0-9_' '\n' | sort -u >"$1"
}

# untested ROWS CORPUS OUT — golden rows whose symbol name is absent from OUT.
untested() { # $1=surface $2=corpus $3=out
	awk 'NR == FNR { seen[$1] = 1; next } { if (!($2 in seen)) print }' \
		"$2" "$1" | sort >"$3"
}

# baseline_keys FILE — data rows with any trailing " # reason" stripped.
baseline_keys() {
	awk '
		/^[[:space:]]*#/ || NF == 0 { next }
		{ sub(/[[:space:]]+#.*$/, ""); print }' "$1" | sort -u
}

# compare CURRENT_KEYS BASELINE_KEYS OUT — prints "NEW <key>" / "STALE <key>".
# Exit: 1 when any NEW key exists.
compare_rows() { # $1=current $2=baseline $3=out
	local rc=0
	awk -v cur_file="$1" -v bl_file="$2" '
		FILENAME == bl_file { bl[$0] = 1; next }
		FILENAME == cur_file { cur[$0] = 1; next }
		END {
			fail = 0
			for (k in cur) if (!(k in bl)) { print "NEW " k; fail = 1 }
			for (k in bl) if (!(k in cur)) print "STALE " k
			exit fail
		}' "$2" "$1" | sort >"$3" || rc=$?
	return "$rc"
}

write_baseline() { # $1=current keys, $2=out, $3=existing baseline (for reasons)
	local date
	date="$(date +%Y-%m-%d)"
	{
		printf '%s\n' \
			"# Untested-export debt list — one exported symbol per row." \
			"# Generated by: bash scripts/check-untested-exports.sh --update" \
			"#" \
			"# Every row is API that NO test file names. Frozen $date at the census" \
			"# of docs/api_surface.txt, so the gate can fail on NEW untested exports" \
			"# without demanding a 1,088-symbol rewrite first. The list only shrinks:" \
			"# give the symbol a test and --update prunes the row." \
			"#" \
			"# To accept a new symbol deliberately, add its row by hand with a reason:" \
			"#   metaengine/func Thing   # reason: only reachable through the docs demo" \
			"# --update preserves a trailing reason on rows that survive." \
			"#" \
			"# Format: <module>/<kind> <Name>"
		if [ -f "$3" ]; then
			# Keep existing reasons for rows that are still untested.
			awk '
				NR == FNR {
					line = $0
					if (line ~ /^[[:space:]]*#/ || line == "") next
					key = line
					sub(/[[:space:]]+#.*$/, "", key)
					reason = substr(line, length(key) + 1)
					if (reason != "") reason_of[key] = reason
					next
				}
				{ print $0 (($0 in reason_of) ? reason_of[$0] : "") }' "$3" "$1"
		else
			cat "$1"
		fi
	} >"$2"
}

self_test() {
	local tmp failures=0 rc out
	tmp="$(mktemp -d)"
	# shellcheck disable=SC2064  # $tmp must expand now, not at trap time
	trap "rm -rf '$tmp'" EXIT

	# Corpus: Alpha and Beta are named by tests; nothing names Gamma.
	# Matching is EXACT, so `TestAlpha` does not count as naming Alpha.
	printf '%s\n' "TestAlpha" "Alpha" "Beta" >"$tmp/corpus.txt"
	printf '%s\n' "mod/func Alpha" "mod/func Beta" "mod/func Gamma" >"$tmp/surface.txt"
	untested "$tmp/surface.txt" "$tmp/corpus.txt" "$tmp/current.txt"

	if ! grep -qx "mod/func Gamma" "$tmp/current.txt" || [ "$(grep -c . "$tmp/current.txt")" -ne 1 ]; then
		echo "self-test FAIL: corpus filtering must keep exactly the unreferenced symbol" >&2
		failures=$((failures + 1))
	fi

	# Everyone on the list: green.
	printf '%s\n' "mod/func Gamma" >"$tmp/bl.txt"
	baseline_keys "$tmp/bl.txt" >"$tmp/blkeys.txt"
	if ! compare_rows "$tmp/current.txt" "$tmp/blkeys.txt" "$tmp/rows.txt" >/dev/null; then
		echo "self-test FAIL: a fully frozen list must be green" >&2
		failures=$((failures + 1))
	fi

	# A NEW untested export: red, and named.
	printf '%s\n' "mod/func Delta" >"$tmp/current-new.txt"
	printf '%s\n' "mod/func Gamma" >>"$tmp/current-new.txt"
	rc=0
	compare_rows "$tmp/current-new.txt" "$tmp/blkeys.txt" "$tmp/rows.txt" || rc=$?
	if [ "$rc" -eq 0 ] || ! grep -q "NEW mod/func Delta" "$tmp/rows.txt"; then
		echo "self-test FAIL: a new untested export must be red and named" >&2
		failures=$((failures + 1))
	fi

	# A row that gained a test: STALE, not a failure.
	printf '%s\n' "mod/func Gamma" "mod/func Beta" >"$tmp/bl-stale.txt"
	baseline_keys "$tmp/bl-stale.txt" >"$tmp/blstale.txt"
	rc=0
	compare_rows "$tmp/current.txt" "$tmp/blstale.txt" "$tmp/rows.txt" || rc=$?
	if [ "$rc" -ne 0 ] || ! grep -q "STALE mod/func Beta" "$tmp/rows.txt"; then
		echo "self-test FAIL: a symbol that gained a test must report STALE without failing" >&2
		failures=$((failures + 1))
	fi

	# Trailing reasons survive --update.
	printf '%s\n' "mod/func Gamma   # reason: docs-only demo" >"$tmp/bl-reason.txt"
	printf '%s\n' "mod/func Gamma" >"$tmp/current2.txt"
	write_baseline "$tmp/current2.txt" "$tmp/newbl.txt" "$tmp/bl-reason.txt"
	if ! grep -q "reason: docs-only demo" "$tmp/newbl.txt"; then
		echo "self-test FAIL: --update must preserve a row's reason" >&2
		failures=$((failures + 1))
	fi

	if [ "$failures" -gt 0 ]; then
		echo "::error::check-untested-exports self-test: $failures case(s) failed" >&2
		exit 1
	fi
	echo "✓ check-untested-exports self-test: 5/5 fault-injection cases behave"
}

if [ "$MODE" = "selftest" ]; then
	self_test
	exit 0
fi

[ -f "$SURFACE" ] || die "API surface '$SURFACE' is missing — run: cd cmd/api-stability && GOWORK=off go run . --update"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

build_corpus "$tmp/corpus.txt"
untested "$SURFACE" "$tmp/corpus.txt" "$tmp/current.txt"
total="$(grep -c . "$SURFACE" || true)"
untested_n="$(grep -c . "$tmp/current.txt" || true)"

if [ "$MODE" = "update" ]; then
	write_baseline "$tmp/current.txt" "$BASELINE" "$BASELINE"
	echo "✓ Wrote $untested_n untested-export rows to $BASELINE"
	echo "  $untested_n of $total exported symbols are named by no test ($(awk -v u="$untested_n" -v t="$total" 'BEGIN{printf "%.1f", 100*u/t}')%)."
	exit 0
fi

[ -f "$BASELINE" ] || die "baseline '$BASELINE' is missing — run: bash scripts/check-untested-exports.sh --update"

baseline_keys "$BASELINE" >"$tmp/blkeys.txt"
rc=0
compare_rows "$tmp/current.txt" "$tmp/blkeys.txt" "$tmp/rows.txt" || rc=$?

new_n="$(grep -c '^NEW ' "$tmp/rows.txt" || true)"
stale_n="$(grep -c '^STALE ' "$tmp/rows.txt" || true)"
[ "$QUIET" -eq 1 ] || grep '^STALE ' "$tmp/rows.txt" | sed 's/^STALE /  STALE (gained a test, prune with --update): /' || true

if [ "$rc" -eq 0 ]; then
	echo "✓ $untested_n/$total exported symbols are untested and frozen ($stale_n stale row(s) prunable)."
	exit 0
fi

echo ""
echo "::error::$new_n exported symbol(s) are named by NO test and are not on the frozen list:"
grep '^NEW ' "$tmp/rows.txt" | sed 's/^NEW /  /' | head -50
echo ""
echo "Add a test that names the symbol, or freeze it deliberately:"
echo "  add the row to $BASELINE with a trailing '# reason: ...'"
echo "Then re-run: bash scripts/check-untested-exports.sh"
exit 1
