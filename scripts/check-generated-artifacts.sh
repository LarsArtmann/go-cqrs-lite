#!/usr/bin/env bash
# check-generated-artifacts: pre-push freshness sweep over every committed
# generated artifact (TODO :324). A push must never ship a stale generated
# file: each leg regenerates (or runs the artifact's own --check gate) and
# fails loudly on drift, so "regenerated but never committed" and "source
# moved but artifact not refreshed" are caught BEFORE the push, not by CI.
#
# Legs (the row's list, all local — the EventCatalog npm render gate is
# network-bound render validation, not a regen+diff, and stays separate):
#   1. docs-ui.css           — scripts/build-docserver-css.sh --check
#   2. error-taxonomy        — scripts/generate-error-taxonomy.sh --check
#                              (needs an erraudit errorflow binary; reuses
#                              the vendored-tarball cache build)
#   3. engine-capabilities   — scripts/check-engine-capabilities.sh (the
#                              gate IS the drift check; --update regenerates)
#   4. api golden            — cmd/api-stability --update, then
#                              git diff --exit-code docs/api_surface.txt;
#                              drift is reported and RESTORED (never
#                              auto-committed)
#   5. catalog architecture  — scripts/check-architecture-reference.sh
#      HTML export             (local go render + self-containment gate)
#
# Modes:
#   (default)  run every leg, print one verdict line per leg, rc 1 on drift
#   --self-test  verify leg registration + the api-golden drift/restore
#                plumbing with a stub regen (fast; never runs real regens)
#   --list     print the leg names and exit
#
# This is a sweep, not a CI gate: the composed #verify already carries the
# per-artifact gates where they exist; this composes them for the pre-push
# window, where staleness otherwise slips through as a green local run.
#
# Every leg_* function dispatches INDIRECTLY through the legs array
# ("${entry#*:}"), which shellcheck cannot see — hence the file-wide
# SC2329 silence; leg registration itself is proven by --self-test.
# shellcheck disable=SC2329
set -uo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
api_surface="$repo_root/docs/api_surface.txt"

# shellcheck source=scripts/go-env.sh
source "$repo_root/scripts/go-env.sh"

# The vendored erraudit cache build (scripts/erraudit-sweep.sh builds it
# from tools/erraudit/*-src.tgz); fall back to any erraudit on PATH.
vendored_erraudit="${XDG_CACHE_HOME:-$HOME/.cache}/erraudit-sweep/erraudit"
if [ -x "$vendored_erraudit" ]; then
	erraudit_bin="$vendored_erraudit"
else
	erraudit_bin="$(command -v erraudit || true)"
fi

leg_docs_ui_css() {
	"$repo_root/scripts/build-docserver-css.sh" --check
}

leg_error_taxonomy() {
	if [ -z "$erraudit_bin" ]; then
		echo "    SKIP: no erraudit binary (run 'nix run .#erraudit' once to build the vendored one)" >&2
		return 3
	fi

	ERRAUDIT_BIN="$erraudit_bin" "$repo_root/scripts/generate-error-taxonomy.sh" --check
}

leg_engine_capabilities() {
	"$repo_root/scripts/check-engine-capabilities.sh"
}

api_surface_check() { # $1 = regen command (stubbed under --self-test)
	local regen_cmd="${1:-}"
	if [ -n "$regen_cmd" ]; then
		"$regen_cmd"
	else
		(cd "$repo_root/cmd/api-stability/v4" && env GOWORK=off go run . --update)
	fi || {
		echo "    regen itself failed" >&2
		return 1
	}

	if git -C "$repo_root" diff --exit-code --quiet -- docs/api_surface.txt; then
		return 0
	fi

	echo "    drift in docs/api_surface.txt:" >&2
	git -C "$repo_root" diff --stat -- docs/api_surface.txt >&2
	# Restore on drift: the regenerated bytes belong to a deliberate
	# regen+commit by the operator, never to this sweep.
	git -C "$repo_root" restore -- docs/api_surface.txt
	echo "    restored; re-run the regen and commit it deliberately:" >&2
	echo "    (cd cmd/api-stability/v4 && GOWORK=off go run . --update)" >&2

	return 1
}

leg_api_surface() {
	[ -f "$api_surface" ] || {
		echo "    $api_surface is missing entirely — run the regen" >&2
		return 1
	}

	api_surface_check
}

leg_architecture_reference() {
	"$repo_root/scripts/check-architecture-reference.sh"
}

legs=(
	"docs-ui.css:leg_docs_ui_css"
	"error-taxonomy:leg_error_taxonomy"
	"engine-capabilities:leg_engine_capabilities"
	"api-surface-golden:leg_api_surface"
	"architecture-export:leg_architecture_reference"
)

self_test() {
	local failures=0

	for entry in "${legs[@]}"; do
		local name="${entry%%:*}"
		if ! declare -f "${entry#*:}" >/dev/null; then
			echo "self-test FAIL: leg $name resolves to no function" >&2
			failures=$((failures + 1))
		fi
	done

	for f in \
		scripts/build-docserver-css.sh \
		scripts/generate-error-taxonomy.sh \
		scripts/check-engine-capabilities.sh \
		scripts/check-architecture-reference.sh \
		cmd/api-stability/v4/main.go; do
		if [ ! -f "$repo_root/$f" ]; then
			echo "self-test FAIL: leg target $f missing" >&2
			failures=$((failures + 1))
		fi
	done

	# api-golden drift/restore plumbing, mutation-style: plant a drift, prove
	# the stub-regen path detects it AND restores the file, then prove the
	# clean path stays green.
	local orig rc
	orig="$(sha256sum "$api_surface")"
	echo "// self-test planted drift" >>"$api_surface"

	rc=0
	api_surface_check true || rc=$?
	if [ "$rc" -ne 1 ]; then
		echo "self-test FAIL: planted drift must be detected (rc=$rc)" >&2
		failures=$((failures + 1))
	fi
	if [ "$(sha256sum "$api_surface")" != "$orig" ]; then
		echo "self-test FAIL: drift must be restored after detection" >&2
		failures=$((failures + 1))
		git -C "$repo_root" restore -- docs/api_surface.txt
	fi

	rc=0
	api_surface_check true || rc=$?
	if [ "$rc" -ne 0 ]; then
		echo "self-test FAIL: clean tree must pass (rc=$rc)" >&2
		failures=$((failures + 1))
	fi

	[ "$failures" -eq 0 ] && echo "self-test: 3 fault classes verified, all green"
	[ "$failures" -eq 0 ]
}

case "${1:-}" in
--self-test)
	self_test
	exit $?
	;;
--list)
	printf '%s\n' "${legs[@]%%:*}"
	exit 0
	;;
"") ;;
*)
	echo "usage: $0 [--self-test|--list]" >&2
	exit 2
	;;
esac

status=0
for entry in "${legs[@]}"; do
	name="${entry%%:*}"
	rc=0
	"${entry#*:}" || rc=$?
	case $rc in
	0) printf '✅ %-24s fresh\n' "$name" ;;
	3) printf '⏭️  %-24s skipped\n' "$name" ;;
	*) printf '❌ %-24s STALE or failed (rc=%d)\n' "$name" "$rc" ;;
	esac
	[ "$rc" -eq 0 ] || [ "$rc" -eq 3 ] || status=1
done

if [ "$status" -eq 0 ]; then
	echo "✓ all generated artifacts fresh"
else
	echo "::error::generated artifacts drifted — regenerate + commit before pushing" >&2
fi
exit "$status"
