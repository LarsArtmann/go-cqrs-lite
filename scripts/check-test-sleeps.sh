#!/usr/bin/env bash
# check-test-sleeps.sh — a fixed `time.Sleep` in a test is a flake generator;
# new ones need a reason.
#
# Why: 182 `time.Sleep(` call sites live in test files (2026-10-26 census).
# Some are legitimate (a deliberate "nothing happens during this window"
# window, a backoff probe), but most are "wait for the goroutine to get there",
# which is exactly the assertion shape that fails on a loaded CI box and passes
# on a laptop. The cure is structural — poll the condition (`Eventually`,
# `synctest`, a channel), do not sleep longer.
#
# This gate freezes today's sites and blocks NEW ones:
#   * a test file with a sleep not in scripts/test-sleeps-baseline.txt fails,
#   * a baselined file may shrink its count but not grow,
#   * a line carrying `//go-sleep:accept <reason>` is exempt (reason mandatory,
#     checked — an empty marker is itself a failure).
#
# Usage: bash scripts/check-test-sleeps.sh [flags]
#   (default)    verify against the frozen counts
#   --update     rewrite the baseline from the current tree
#   --self-test  fault-inject the compare logic against fixtures
#   --help
#
# Environment: TEST_SLEEPS_BASELINE (default scripts/test-sleeps-baseline.txt)

set -euo pipefail
export LC_ALL=C

cd "$(git rev-parse --show-toplevel)"

BASELINE="${TEST_SLEEPS_BASELINE:-scripts/test-sleeps-baseline.txt}"
MODE=gate

die() {
	echo "::error::$1" >&2
	exit 1
}

usage() {
	sed -n '2,/^$/p' "$0" | sed 's/^# \{0,1\}//'
}

while [ $# -gt 0 ]; do
	case "$1" in
	--update) MODE=update ;;
	--self-test) MODE=selftest ;;
	--help | -h)
		usage
		exit 0
		;;
	*) die "unknown flag: $1 (try --help)" ;;
	esac
	shift
done

# census FILE OUT — "<file>\t<count>" for every test file with an unaccepted
# time.Sleep. The annotation must sit on the sleep line or the line above it.
census() { # $1=root $2=out
	local root="$1"
	: >"$2"
	while IFS= read -r file; do
		local count=0 prev_ok=0
		while IFS= read -r line; do
			case "$line" in
			*"//go-sleep:accept"*)
				# A marker with no reason is a failure in its own right.
				if ! printf '%s' "$line" | grep -qE '//go-sleep:accept[[:space:]]+[^[:space:]]'; then
					echo "::error::${file}: empty //go-sleep:accept marker (a reason is required)" >&2
					return 1
				fi
				prev_ok=1
				continue
				;;
			esac
			case "$line" in
			*"time.Sleep("*)
				if [ "$prev_ok" -eq 0 ]; then
					count=$((count + 1))
				fi
				;;
			esac
			prev_ok=0
		done <"$root/$file"
		[ "$count" -gt 0 ] && printf '%s\t%d\n' "$file" "$count" >>"$2"
	done < <(cd "$root" && grep -rl --include='*_test.go' 'time\.Sleep(' . |
		grep -v '^./vendor/' | grep -v '/testdata/' | grep -v '^./node_modules/' |
		sed 's|^\./||' | sort)
	return 0
}

# compare CENSUS BASELINE OUT — prints "NEW <file> <n>" / "GREW <file> <old> -> <new>".
# Exit: 1 when any file is new or grew.
compare_counts() { # $1=current $2=baseline $3=out
	local rc=0
	awk -F'\t' -v cur_file="$1" -v bl_file="$2" '
		FILENAME == bl_file { bl[$1] = $2; next }
		FILENAME == cur_file { cur[$1] = $2; next }
		END {
			fail = 0
			for (f in cur) {
				if (!(f in bl)) { printf "NEW %s %d\n", f, cur[f]; fail = 1 }
				else if (cur[f] + 0 > bl[f] + 0) { printf "GREW %s %d -> %d\n", f, bl[f], cur[f]; fail = 1 }
			}
			exit fail
		}' "$2" "$1" | sort >"$3" || rc=$?
	return "$rc"
}

write_baseline() { # $1=current census, $2=out
	{
		printf '%s\n' \
			"# Frozen time.Sleep sites in test files." \
			"# Generated by: bash scripts/check-test-sleeps.sh --update" \
			"#" \
			"# A fixed sleep in a test is a flake generator: it asserts \"the" \
			"# goroutine got there by now\" with a number that is only true on an" \
			"# idle laptop. Frozen so NEW sleeps fail and existing counts may only" \
			"# shrink. For a genuine \"nothing happens during this window\" sleep," \
			"# annotate the line with: //go-sleep:accept <reason>" \
			"#" \
			"# file	count"
		sort "$1"
	} >"$2"
}

self_test() {
	local tmp failures=0 rc out
	tmp="$(mktemp -d)"
	# shellcheck disable=SC2064
	trap "rm -rf '$tmp'" EXIT

	mkdir -p "$tmp/tree"
	cat >"$tmp/tree/a_test.go" <<'EOF'
package a

import "time"

func TestA(t *testing.T) {
	time.Sleep(10 * time.Millisecond)
	//go-sleep:accept deliberate quiet window for the negative assertion
	time.Sleep(20 * time.Millisecond)
}
EOF
	cat >"$tmp/tree/b_test.go" <<'EOF'
package a

import "time"

func TestB(t *testing.T) { time.Sleep(time.Second) }
EOF
	census "$tmp/tree" "$tmp/current.txt" || failures=$((failures + 1))

	if [ "$(grep -c . "$tmp/current.txt")" -ne 2 ] || ! grep -q '^a_test.go	1$' "$tmp/current.txt"; then
		echo "self-test FAIL: the accepted sleep must not be counted" >&2
		failures=$((failures + 1))
	fi

	printf 'a_test.go\t1\nb_test.go\t1\n' >"$tmp/bl.txt"
	if ! compare_counts "$tmp/current.txt" "$tmp/bl.txt" "$tmp/rows.txt" >/dev/null; then
		echo "self-test FAIL: a matching census must be green" >&2
		failures=$((failures + 1))
	fi

	printf 'a_test.go\t0\nb_test.go\t1\n' >"$tmp/bl.txt"
	rc=0
	compare_counts "$tmp/current.txt" "$tmp/bl.txt" "$tmp/rows.txt" || rc=$?
	if [ "$rc" -eq 0 ] || ! grep -q "GREW a_test.go" "$tmp/rows.txt"; then
		echo "self-test FAIL: a grown count must be red" >&2
		failures=$((failures + 1))
	fi

	printf 'a_test.go\t1\n' >"$tmp/bl.txt"
	rc=0
	compare_counts "$tmp/current.txt" "$tmp/bl.txt" "$tmp/rows.txt" || rc=$?
	if [ "$rc" -eq 0 ] || ! grep -q "NEW b_test.go" "$tmp/rows.txt"; then
		echo "self-test FAIL: a new sleeping file must be red" >&2
		failures=$((failures + 1))
	fi

	# Shrinking is legitimate.
	printf 'a_test.go\t5\nb_test.go\t4\n' >"$tmp/bl.txt"
	if ! compare_counts "$tmp/current.txt" "$tmp/bl.txt" "$tmp/rows.txt" >/dev/null; then
		echo "self-test FAIL: a shrunk count must be green" >&2
		failures=$((failures + 1))
	fi

	# Empty marker: loud failure.
	cat >"$tmp/tree/c_test.go" <<'EOF'
package a

import "time"

func TestC(t *testing.T) {
	//go-sleep:accept
	time.Sleep(time.Millisecond)
}
EOF
	rc=0
	census "$tmp/tree" "$tmp/current2.txt" 2>/dev/null || rc=$?
	if [ "$rc" -eq 0 ]; then
		echo "self-test FAIL: an empty //go-sleep:accept must fail" >&2
		failures=$((failures + 1))
	fi

	if [ "$failures" -gt 0 ]; then
		echo "::error::check-test-sleeps self-test: $failures case(s) failed" >&2
		exit 1
	fi
	echo "✓ check-test-sleeps self-test: 6/6 fault-injection cases behave"
}

if [ "$MODE" = "selftest" ]; then
	self_test
	exit 0
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
census "$PWD" "$tmp/current.txt"
total="$(awk -F'\t' '{s += $2} END {print s + 0}' "$tmp/current.txt")"

if [ "$MODE" = "update" ]; then
	write_baseline "$tmp/current.txt" "$BASELINE"
	echo "✓ Wrote $(grep -vc '^#' "$BASELINE") files / $total unaccepted sleeps to $BASELINE"
	exit 0
fi

[ -f "$BASELINE" ] || die "baseline '$BASELINE' is missing — run: bash scripts/check-test-sleeps.sh --update"
rc=0
compare_counts "$tmp/current.txt" "$BASELINE" "$tmp/rows.txt" || rc=$?
if [ "$rc" -eq 0 ]; then
	echo "✓ $total frozen test sleeps, none new (annotate deliberate ones with //go-sleep:accept <reason>)."
	exit 0
fi
echo "::error::new or grown time.Sleep in tests:"
sed 's/^/  /' "$tmp/rows.txt"
echo ""
echo "Poll the condition instead of sleeping: Eventually/channel/clock advance."
echo "A genuine quiet window keeps a reason: //go-sleep:accept <reason>"
exit 1
