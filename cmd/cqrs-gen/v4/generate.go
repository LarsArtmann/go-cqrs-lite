package main

import (
	"fmt"
	"go/format"
	"strings"
)

const (
	pathCommand = "github.com/larsartmann/go-cqrs-lite/command/v4"
	pathEvent   = "github.com/larsartmann/go-cqrs-lite/event/v4"
	pathID      = "github.com/larsartmann/go-cqrs-lite/id/v4"
	pathQuery   = "github.com/larsartmann/go-cqrs-lite/query/v4"
	pathSystem  = "github.com/larsartmann/go-cqrs-lite/system/v4"
	pathCatalog = "github.com/larsartmann/go-cqrs-lite/catalog/v4"

	pathContext = "context"
	pathFmt     = "fmt"

	localPrefix = "github.com/larsartmann/go-cqrs-lite/"
)

const (
	directionSends    = "catalog.Sends"
	directionReceives = "catalog.Receives"
)

func generate(p pkg, opts genOptions) (string, error) {
	var b strings.Builder

	b.WriteString("// Code generated by cqrs-gen. DO NOT EDIT.\n\n")

	fmt.Fprintf(&b, "package %s\n\n", p.name)

	b.WriteString(importBlock(p, opts))
	writeConstants(&b, p)

	for i := range p.markers {
		writeMarker(&b, &p.markers[i], opts)
	}

	if opts.catalog {
		writeCatalog(&b, p)
	}

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return "", fmt.Errorf("format generated code for %s: %w\n--- generated source ---\n%s",
			p.dir, err, b.String())
	}

	return string(formatted), nil
}

// importBlock mirrors the grouping goimports -local produces, so a generated
// file survives the fleet's formatters byte for byte.
func importBlock(p pkg, opts genOptions) string {
	paths := uniqueSorted(requiredImports(p, opts))

	std, other, local := splitImports(paths)

	var b strings.Builder

	b.WriteString("import (\n")

	for _, group := range [][]string{std, other, local} {
		if len(group) == 0 {
			continue
		}

		if b.Len() > len("import (\n") {
			b.WriteString("\n")
		}

		for _, path := range group {
			fmt.Fprintf(&b, "\t%q\n", path)
		}
	}

	b.WriteString(")\n\n")

	return b.String()
}

func splitImports(paths []string) ([]string, []string, []string) {
	var std, other, local []string

	for _, path := range paths {
		switch {
		case !strings.Contains(strings.SplitN(path, "/", 2)[0], "."):
			std = append(std, path)
		case strings.HasPrefix(path, localPrefix):
			local = append(local, path)
		default:
			other = append(other, path)
		}
	}

	return std, other, local
}

func requiredImports(p pkg, opts genOptions) []string {
	var paths []string

	for _, m := range p.markers {
		switch m.kind {
		case kindCommand:
			paths = append(paths, pathContext)

			if m.constExpr != "" || opts.target == targetDispatcher {
				paths = append(paths, pathCommand)
			}

			if opts.target == targetSystem {
				paths = append(paths, pathSystem, pathID, pathEvent)
			}
		case kindQuery:
			paths = append(paths, pathContext)

			if m.constExpr != "" || opts.target == targetDispatcher {
				paths = append(paths, pathQuery)
			}

			if opts.target == targetSystem {
				paths = append(paths, pathSystem)
			}
		case kindEvent:
			paths = append(paths, pathEvent, pathID, pathFmt)

			if opts.handlers {
				paths = append(paths, pathContext)
			}
		}
	}

	if opts.catalog {
		paths = append(paths, pathCatalog)
	}

	return paths
}

func writeConstants(b *strings.Builder, p pkg) {
	var generated []marker

	for _, m := range p.markers {
		if m.constExpr != "" {
			generated = append(generated, m)
		}
	}

	if len(generated) == 0 {
		return
	}

	b.WriteString("const (\n")

	for _, m := range generated {
		fmt.Fprintf(b, "\t%s %s = %s\n", m.constName, typeName(m.kind), m.constExpr)
	}

	b.WriteString(")\n\n")
}

func writeMarker(b *strings.Builder, m *marker, opts genOptions) {
	switch m.kind {
	case kindCommand:
		if opts.target == targetSystem {
			writeSystemCommand(b, m)
		} else {
			writeDispatcherCommand(b, m)
		}
	case kindQuery:
		if opts.target == targetSystem {
			writeSystemQuery(b, m)
		} else {
			writeDispatcherQuery(b, m)
		}
	case kindEvent:
		writeEventConstructor(b, m)

		if opts.handlers {
			writeEventHandler(b, m)
		}
	}
}

func writeSystemCommand(b *strings.Builder, m *marker) {
	value := m.valueType()

	fmt.Fprintf(b, "// %s registers %s on the composition root.\n"+
		"// decide runs against the state folded from the command's stream.\n", registerName(m), m.wire)
	fmt.Fprintf(b, "func %s[State any](\n", registerName(m))
	b.WriteString("\tsys *system.System,\n")
	b.WriteString("\tstreamType id.StreamType,\n")
	fmt.Fprintf(b, "\tdecide func(context.Context, %s, State, event.Version) ([]event.Event, error),\n", value)
	b.WriteString(") error {\n")
	fmt.Fprintf(b, "\treturn system.RegisterCommand[%s, State](sys, %s, "+
		"func(ctx context.Context, cmd %s) system.Op[State] {\n", value, m.constName, value)
	b.WriteString("\t\treturn system.Execute(ctx, cmd.StreamID(), streamType, " +
		"func(state State, version event.Version) ([]event.Event, error) {\n")
	b.WriteString("\t\t\treturn decide(ctx, cmd, state, version)\n")
	b.WriteString("\t\t})\n")
	b.WriteString("\t})\n")
	b.WriteString("}\n\n")
}

func writeSystemQuery(b *strings.Builder, m *marker) {
	value := m.valueType()

	fmt.Fprintf(b, "// %s registers %s on the composition root.\n", registerName(m), m.wire)
	fmt.Fprintf(b, "func %s[R any](\n", registerName(m))
	b.WriteString("\tsys *system.System,\n")
	fmt.Fprintf(b, "\thandler func(context.Context, %s) (R, error),\n", value)
	b.WriteString(") error {\n")
	fmt.Fprintf(b, "\treturn system.RegisterQuery[%s, R](sys, string(%s), handler)\n",
		value, m.constName)
	b.WriteString("}\n\n")
}

func writeDispatcherCommand(b *strings.Builder, m *marker) {
	value := m.valueType()

	fmt.Fprintf(b, "// %s registers a typed handler for %s commands.\n", handlerName(m), m.wire)
	fmt.Fprintf(b, "func %s(\n", handlerName(m))
	b.WriteString("\td *command.Dispatcher,\n")
	fmt.Fprintf(b, "\thandler func(context.Context, %s) error,\n", value)
	b.WriteString(") error {\n")
	fmt.Fprintf(b, "\treturn command.RegisterTyped[%s](d, %s, handler)\n", value, m.constName)
	b.WriteString("}\n\n")
}

func writeDispatcherQuery(b *strings.Builder, m *marker) {
	value := m.valueType()

	fmt.Fprintf(b, "// %s registers a typed handler for %s queries.\n", handlerName(m), m.wire)
	fmt.Fprintf(b, "func %s[R any](\n", handlerName(m))
	b.WriteString("\td *query.Dispatcher,\n")
	fmt.Fprintf(b, "\thandler func(context.Context, %s) (R, error),\n", value)
	b.WriteString(") error {\n")
	fmt.Fprintf(b, "\treturn query.RegisterTyped[%s, R](d, %s, handler)\n", value, m.constName)
	b.WriteString("}\n\n")
}

func writeEventConstructor(b *strings.Builder, m *marker) {
	fmt.Fprintf(b, "// %s builds the %s event for a stream.\n", eventName(m), m.wire)
	fmt.Fprintf(b, "func %s(\n", eventName(m))
	b.WriteString("\tstreamID id.StreamID,\n")
	b.WriteString("\tstreamType id.StreamType,\n")
	b.WriteString("\tversion event.Version,\n")
	fmt.Fprintf(b, "\tpayload %s,\n) (event.Event, error) {\n", m.structName)
	fmt.Fprintf(b, "\tevt, err := event.New(%s, streamID, streamType, version, payload)\n", m.constName)
	fmt.Fprintf(b, "\tif err != nil {\n\t\treturn nil, fmt.Errorf(\"%%s: %%w\", %s, err)\n\t}\n\n", m.constName)
	b.WriteString("\treturn evt, nil\n}\n\n")
}

func writeEventHandler(b *strings.Builder, m *marker) {
	fmt.Fprintf(b, "// %s subscribes handler to %s events.\n", handlerName(m), m.wire)
	fmt.Fprintf(b, "func %s(bus event.Subscriber, handler func(context.Context, %s) error) error {\n",
		handlerName(m), m.structName)
	fmt.Fprintf(b, "\treturn bus.Subscribe(%s, func(ctx context.Context, evt event.Event) error {\n",
		m.constName)
	fmt.Fprintf(b, "\t\tpayload, err := event.DecodePayloadAuto[%s](evt)\n", m.structName)
	b.WriteString("\t\tif err != nil {\n\t\t\treturn err\n\t\t}\n\n")
	b.WriteString("\t\treturn handler(ctx, payload)\n\t})\n}\n\n")
}

func writeCatalog(b *strings.Builder, p pkg) {
	fmt.Fprintf(b, "// %s returns the catalog declarations of every marked message in this package.\n",
		catalogFunc)
	fmt.Fprintf(b, "func %s(opts ...catalog.MessageOption) []catalog.MessageConfig {\n", catalogFunc)
	b.WriteString("\treturn []catalog.MessageConfig{\n")

	for i := range p.markers {
		writeCatalogMessage(b, &p.markers[i])
	}

	b.WriteString("\t}\n}\n")
}

func writeCatalogMessage(b *strings.Builder, m *marker) {
	switch m.kind {
	case kindCommand:
		fmt.Fprintf(b, "\t\tcatalog.Command[%s](catalog.MessageID(%s), opts...),\n",
			m.structName, m.constName)
	case kindQuery:
		fmt.Fprintf(b, "\t\tcatalog.Query[%s](catalog.MessageID(%s), opts...),\n",
			m.structName, m.constName)
	case kindEvent:
		direction := directionSends
		if m.receives {
			direction = directionReceives
		}

		fmt.Fprintf(b, "\t\tcatalog.Event[%s](catalog.MessageID(%s), %s, opts...),\n",
			m.structName, m.constName, direction)
	}
}
