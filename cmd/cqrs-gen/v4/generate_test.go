func TestGenerate_ReferenceKeepsPackageConstant(t *testing.T) {
	sources := map[string]string{
		"commands.go": "package tasks\n\nconst cmdCreateTask = command.Type(\"task.create\")\n\n" +
			"//cqrs:command task.create\ntype CreateTaskCmd struct{}",
	}

	code := mustGenerate(t, scanFixture(t, sources), genOptions{target: targetSystem})

	if strings.Contains(code, "CommandCreateTask") || strings.Contains(code, `"task.create"`) {
		t.Errorf("the package constant must stay the single source of the wire name, got:\n%s", code)
	}

	if !strings.Contains(code, "system.RegisterCommand[*CreateTaskCmd, State](sys, cmdCreateTask,") {
		t.Errorf("registration must reference the package constant, got:\n%s", code)
	}

	if strings.Contains(code, "const (") {
		t.Errorf("no constant must be emitted next to the package's own, got:\n%s", code)
	}

	if strings.Contains(code, "\""+pathCommand+"\"") {
		t.Errorf("a referenced constant needs no command import, got:\n%s", code)
	}
}

func TestImportBlockGroups(t *testing.T) {
	std, other, local := splitImports(uniqueSorted([]string{
		pathSystem, pathContext, "github.com/spf13/cobra", pathFmt, pathCommand,
	}))

	if !slices.Equal(std, []string{pathContext, pathFmt}) {
		t.Errorf("std imports = %q", std)
	}

	if !slices.Equal(other, []string{"github.com/spf13/cobra"}) {
		t.Errorf("other imports = %q", other)
	}

	if !slices.Equal(local, []string{pathCommand, pathSystem}) {
		t.Errorf("local imports = %q", local)
	}
}
