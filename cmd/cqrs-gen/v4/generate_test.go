func TestGenerate_ValueFormForEnvelopeEmbeds(t *testing.T) {
	sources := map[string]string{
		"commands.go": "package tasks\n\n//cqrs:command task.create\n" +
			"type CreateTaskCmd struct {\n\t*command.BasicCommand\n}",
		"queries.go": "package tasks\n\n//cqrs:query task.get\n" +
			"type GetTask struct {\n\t*query.BasicQuery\n}",
	}

	code := mustGenerate(t, scanFixture(t, sources), genOptions{target: targetSystem})

	want := []string{
		"decide func(context.Context, CreateTaskCmd, State, event.Version) ([]event.Event, error),",
		"func(ctx context.Context, cmd CreateTaskCmd) system.Op[State] {",
		"handler func(context.Context, GetTask) (R, error),",
		"system.RegisterQuery[GetTask, R](sys, string(QueryGetTask), handler)",
	}

	for _, line := range want {
		if !strings.Contains(code, line) {
			t.Errorf("missing %s in:\n%s", line, code)
		}
	}

	if strings.Contains(code, "*CreateTaskCmd") || strings.Contains(code, "*GetTask") {
		t.Errorf("structs embedding the envelope by pointer are passed by value, got:\n%s", code)
	}
}

func TestGenerate_QueryOnlyImports(t *testing.T) {
	sources := map[string]string{
		"queries.go": "package tasks\n\n//cqrs:query task.get\ntype GetTask struct{ ID string }",
	}

	code := mustGenerate(t, scanFixture(t, sources), genOptions{target: targetSystem})

	wantImports := []string{
		"\"context\"",
		"\"github.com/larsartmann/go-cqrs-lite/query/v4\"",
		"\"github.com/larsartmann/go-cqrs-lite/system/v4\"",
	}

	referenced := mustGenerate(t, scanFixture(t, map[string]string{
		"queries.go": "package tasks\n\nconst qryGetTask = query.Type(\"task.get\")\n\n" +
			"//cqrs:query task.get\ntype GetTask struct{}",
	}), genOptions{target: targetSystem})
	if strings.Contains(referenced, "\""+pathQuery+"\"") {
		t.Errorf("a referenced constant needs no query import, got:\n%s", referenced)
	}

	for _, path := range wantImports {
		if !strings.Contains(code, "\t"+path+"\n") {
			t.Errorf("query-only package must import %s, got:\n%s", path, code)
		}
	}

	for _, path := range []string{"command/v4", "event/v4", "id/v4", "fmt"} {
		if strings.Contains(code, path) {
			t.Errorf("query-only package must not import %s, got:\n%s", path, code)
		}
	}
}

