func TestGenerate_EventHandlersAreOptIn(t *testing.T) {
	pkgs := scanFixture(t, markedSources)

	plain := mustGenerate(t, pkgs, genOptions{target: targetSystem})
	if strings.Contains(plain, "RegisterTaskCreatedHandler") {
		t.Errorf("event subscription handlers must be opt-in, got:\n%s", plain)
	}

	withHandlers := mustGenerate(t, pkgs, genOptions{target: targetSystem, handlers: true})

	want := "func RegisterTaskCreatedHandler(bus event.Subscriber, " +
		"handler func(context.Context, TaskCreated) error) error {"
	if !strings.Contains(withHandlers, want) {
		t.Errorf("missing %s in:\n%s", want, withHandlers)
	}

	if !strings.Contains(withHandlers, "payload, err := event.DecodePayloadAuto[TaskCreated](evt)") {
		t.Errorf("handler must decode with the self-describing codec, got:\n%s", withHandlers)
	}
}

