func scanFixture(t *testing.T, sources map[string]string) []pkg {
	t.Helper()

	root := t.TempDir()

	for name, content := range sources {
		writeFixture(t, root, "tasks/"+name, content)
	}

	pkgs, err := scan([]string{root}, mustKinds(t, kindAll))
	if err != nil {
		t.Fatalf("scan: %v", err)
	}

	return pkgs
}

func mustGenerate(t *testing.T, pkgs []pkg, opts genOptions) string {
	t.Helper()

	if len(pkgs) != 1 {
		t.Fatalf("expected one package, got %v", summarize(pkgs))
	}

	code, err := generate(pkgs[0], opts)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}

	return code
}

func assertGolden(t *testing.T, got, want string) {
	t.Helper()

	if got != want {
		gotLines, wantLines := strings.Split(got, "\n"), strings.Split(want, "\n")

		for i := range max(len(gotLines), len(wantLines)) {
			g, w := "<missing>", "<missing>"
			if i < len(gotLines) {
				g = gotLines[i]
			}

			if i < len(wantLines) {
				w = wantLines[i]
			}

			if g != w {
				t.Errorf("generated code differs at line %d:\n got: %s\nwant: %s", i+1, g, w)
			}
		}
	}
}

