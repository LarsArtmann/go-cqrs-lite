package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// goFences returns the body of every ```go fence of a Markdown file, in
// document order.
func goFences(t *testing.T, path string) []string {
	t.Helper()

	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}

	var (
		fences  []string
		body    strings.Builder
		inFence bool
	)

	for line := range strings.SplitSeq(string(raw), "\n") {
		switch {
		case !inFence && strings.HasPrefix(line, "```go"):
			inFence = true

			body.Reset()
		case inFence && line == "```":
			fences = append(fences, body.String())

			inFence = false
		case inFence:
			body.WriteString(line + "\n")
		}
	}

	return fences
}

// TestReadme_ShowsRealOutput keeps the README's generated-output fence equal
// to what the generator writes for the README's own marker example, so the
// documented output can never drift from the real one.
func TestReadme_ShowsRealOutput(t *testing.T) {
	t.Parallel()

	fences := goFences(t, filepath.Join("README.md"))
	if len(fences) < 3 {
		t.Fatalf("README.md carries %d Go fences, want at least the markers and the output", len(fences))
	}

	var shown string

	for _, fence := range fences {
		if strings.HasPrefix(fence, "// Code generated by cqrs-gen.") {
			shown = fence

			break
		}
	}

	if shown == "" {
		t.Fatal("README.md must carry the generator's complete output as a Go fence")
	}

	markers := fences[0]

	dir := t.TempDir()

	writeFixture(t, dir, "domain.go", "package users\n\n"+markers)

	pkgs, err := scan([]string{dir}, mustKinds(t, kindAll))
	if err != nil {
		t.Fatalf("scan the README markers: %v", err)
	}

	if len(pkgs) != 1 || len(pkgs[0].markers) != 3 {
		t.Fatalf("the README marker example must declare three marked structs in one package, got %s",
			summarize(pkgs))
	}

	assertGolden(t, mustGenerate(t, pkgs, genOptions{target: targetSystem, catalog: true}), shown)
}
