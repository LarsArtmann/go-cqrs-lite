package main

import (
	"strings"
	"testing"
)

var envelopeSources = map[string]string{
	"commands.go": "package tasks\n\n//cqrs:command task.create\ntype CreateTaskCmd struct {\n\t*command.BasicCommand\n\tTitle string\n}",
	"queries.go":  "package tasks\n\n//cqrs:query task.get\ntype GetTask struct {\n\t*query.BasicQuery\n}",
}

const envelopeGolden = `// Code generated by cqrs-gen. DO NOT EDIT.

package tasks

import (
	"context"

	"github.com/larsartmann/go-cqrs-lite/command/v4"
	"github.com/larsartmann/go-cqrs-lite/event/v4"
	"github.com/larsartmann/go-cqrs-lite/id/v4"
	"github.com/larsartmann/go-cqrs-lite/query/v4"
	"github.com/larsartmann/go-cqrs-lite/system/v4"
)

const (
	CommandCreateTask command.Type = "task.create"
	QueryGetTask      query.Type   = "task.get"
)

// NewCreateTaskCmd stamps the task.create envelope onto the payload; options reach the library constructor.
func NewCreateTaskCmd(
	streamID id.StreamID,
	payload CreateTaskCmd,
	opts ...command.Option,
) (CreateTaskCmd, error) {
	basic, err := command.New(CommandCreateTask, streamID, opts...)
	if err != nil {
		return CreateTaskCmd{}, err
	}

	payload.BasicCommand = basic

	return payload, nil
}

// RegisterCreateTaskCmd registers task.create on the composition root.
// decide runs against the state folded from the command's stream.
func RegisterCreateTaskCmd[State any](
	sys *system.System,
	streamType id.StreamType,
	decide func(context.Context, CreateTaskCmd, State, event.Version) ([]event.Event, error),
) error {
	return system.RegisterCommand[CreateTaskCmd, State](sys, CommandCreateTask, func(ctx context.Context, cmd CreateTaskCmd) system.Op[State] {
		return system.Execute(ctx, cmd.StreamID(), streamType, func(state State, version event.Version) ([]event.Event, error) {
			return decide(ctx, cmd, state, version)
		})
	})
}

// NewGetTask stamps the task.get envelope onto the payload; options reach the library constructor.
func NewGetTask(
	payload GetTask,
	opts ...query.Option,
) (GetTask, error) {
	basic, err := query.New(QueryGetTask, opts...)
	if err != nil {
		return GetTask{}, err
	}

	payload.BasicQuery = basic

	return payload, nil
}

// RegisterGetTask registers task.get on the composition root.
func RegisterGetTask[R any](
	sys *system.System,
	handler func(context.Context, GetTask) (R, error),
) error {
	return system.RegisterQuery[GetTask, R](sys, string(QueryGetTask), handler)
}
`

func TestGenerate_EnvelopeGolden(t *testing.T) {
	t.Parallel()

	code := mustGenerate(t, scanFixture(t, envelopeSources), genOptions{target: targetSystem})

	assertGolden(t, code, envelopeGolden)
}

// A hand-written New<Struct> may carry validation, so the generator leaves it
// the only constructor instead of failing on the name.
func TestGenerate_HandWrittenConstructorKeepsItsPlace(t *testing.T) {
	t.Parallel()

	code := mustGenerate(t, scanFixture(t, map[string]string{
		"commands.go": "package tasks\n\n//cqrs:command task.create\ntype CreateTaskCmd struct {\n\t*command.BasicCommand\n}\n\n" +
			"func NewCreateTaskCmd(title string) *CreateTaskCmd { return nil }",
	}), genOptions{target: targetSystem})

	if strings.Contains(code, "NewCreateTaskCmd(") || strings.Contains(code, "payload.BasicCommand = basic") {
		t.Errorf("a hand-written constructor must stay the only one, got:\n%s", code)
	}

	if !strings.Contains(code, "func RegisterCreateTaskCmd[State any](") {
		t.Errorf("the registration is still derived, got:\n%s", code)
	}
}

// A message without the envelope embed carries its own identity: nothing in
// its construction is derivable from the marker.
func TestGenerate_NoConstructorWithoutEnvelopeEmbed(t *testing.T) {
	t.Parallel()

	code := mustGenerate(t, scanFixture(t, markedSources), genOptions{target: targetSystem})

	if strings.Contains(code, "func NewCreateTaskCmd(") || strings.Contains(code, "func NewGetTask(") {
		t.Errorf("only an envelope embed yields a constructor, got:\n%s", code)
	}
}

func TestGenerate_DispatcherTargetDerivesConstructors(t *testing.T) {
	t.Parallel()

	code := mustGenerate(t, scanFixture(t, envelopeSources), genOptions{target: targetDispatcher})

	for _, want := range []string{
		"func NewCreateTaskCmd(\n\tstreamID id.StreamID,\n\tpayload CreateTaskCmd,\n\topts ...command.Option,\n" +
			") (CreateTaskCmd, error) {",
		"func NewGetTask(\n\tpayload GetTask,\n\topts ...query.Option,\n) (GetTask, error) {",
		"func RegisterCreateTaskCmdHandler(",
		"\"" + pathCommand + "\"",
		"\"" + pathID + "\"",
		"\"" + pathQuery + "\"",
	} {
		if !strings.Contains(code, want) {
			t.Errorf("missing %s in:\n%s", want, code)
		}
	}
}
