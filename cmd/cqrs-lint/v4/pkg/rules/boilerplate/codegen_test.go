package boilerplate_test

import (
	"strings"
	"testing"

	"github.com/larsartmann/go-cqrs-lite/cmd/cqrs-lint/v4/pkg/analyzer"
	"github.com/larsartmann/go-cqrs-lite/cmd/cqrs-lint/v4/pkg/rules/boilerplate"
	"github.com/larsartmann/go-cqrs-lite/cmd/cqrs-lint/v4/pkg/ruletest"
)

const generatedHeader = "// Code generated by cqrs-gen. DO NOT EDIT.\n\n"

const emitHelper = `package main

func emitCreated(bus *Bus, id string) {
	evt, _ := event.New("created", id, "User", 1, payload)
	bus.Publish(evt)
}
`

const catalogList = `package main

func registerCatalog(r *Registry) {
	catalog.Event("user.created", UserCreated{})
	catalog.Event("user.updated", UserUpdated{})
	catalog.Event("user.deleted", UserDeleted{})
}
`

// B009 and B010 must stay silent inside a generated file: cqrs-gen's own
// output is an emit helper and a catalog list by construction, so without the
// skip each rule flags the very code that resolves it.
func TestB009_GeneratedFileIsSilent(t *testing.T) {
	t.Parallel()

	hand := analyzer.BuildContextFromSource(t, map[string]string{"emit.go": emitHelper})
	ruletest.AssertRule(t, ruletest.RunDetector(t, boilerplate.NewB009Detector(hand)), "B009", 1)

	gen := analyzer.BuildContextFromSource(t, map[string]string{"cqrs_gen.go": generatedHeader + emitHelper})
	ruletest.AssertRule(t, ruletest.RunDetector(t, boilerplate.NewB009Detector(gen)), "B009", 0)
}

func TestB010_GeneratedFileIsSilent(t *testing.T) {
	t.Parallel()

	hand := analyzer.BuildContextFromSource(t, map[string]string{"catalog.go": catalogList})
	ruletest.AssertRule(t, ruletest.RunDetector(t, boilerplate.NewB010Detector(hand)), "B010", 1)

	gen := analyzer.BuildContextFromSource(t, map[string]string{"cqrs_gen.go": generatedHeader + catalogList})
	ruletest.AssertRule(t, ruletest.RunDetector(t, boilerplate.NewB010Detector(gen)), "B010", 0)
}

// B004 may only promise what cqrs-gen writes: the marker and the constructor
// it derives for the flagged command.
func TestB004_PointsAtMarkerAndConstructor(t *testing.T) {
	t.Parallel()

	ctx := analyzer.BuildContextFromSource(t, map[string]string{
		"cmd.go": `package main

type CreateOrder struct {
	*BasicCommand
	CustomerID string
	ProductID  string
	Quantity   int
}
`,
	})

	findings := ruletest.RunDetector(t, boilerplate.NewB004Detector(ctx))
	ruletest.AssertRule(t, findings, "B004", 1)

	for _, f := range findings {
		if string(f.Rule) != "B004" {
			continue
		}

		if !strings.Contains(f.Message, "//cqrs:command") || !strings.Contains(f.Suggestion, "NewCreateOrder") {
			t.Errorf("B004 must name the marker and the derived constructor, got %q and %q",
				f.Message, f.Suggestion)
		}
	}
}
